package kafkax

import (
	"context"
	"crypto/tls"
	"errors"
	"fmt"
	"log/slog"

	"github.com/twmb/franz-go/pkg/kgo"
)

// Здесь живёт поведение клиента — всё, что нельзя записать в yaml или в
// переменную окружения: логгер, готовый *tls.Config, аварийный выход в опции
// franz-go и два пользовательских хука.
//
// Раньше эти пять вещей лежали в Config рядом с адресами брокеров и таймаутами,
// под тегами yaml:"-". Одна структура несла две несовместимые сущности:
// сериализуемые данные, которые cleanenv читает из файла и окружения, и живые
// значения, которые может подставить только код. Разделение стоит того:
// Config снова целиком читается из конфигурации, а поведение задаётся там, где
// клиент создаётся, — типизированными опциями с собственным godoc.

// PanicHook вызывается после восстановления паники в горутине библиотеки.
// site — точка восстановления (см. PanicSite и константы PanicSite*),
// recovered — значение из recover(), stack — стек на момент паники.
//
// Вызывается синхронно из той горутины, где произошла паника: не должен
// блокироваться надолго. Собственная паника хука перехватывается — с записью в
// лог и инкрементом kafkax.consumer.panics{site="on_panic"}, но без повторного
// вызова самого хука: рекурсия в обработчике паник кончилась бы переполнением
// стека.
//
// На панику обработчика вызывается один раз на сообщение, а не на попытку: при
// HandlerMaxRetries = -1 второе означало бы вызов без конца.
type PanicHook func(ctx context.Context, site PanicSite, recovered any, stack []byte)

// SkipHook решает судьбу сообщения, которое обработчик не осилил за
// Consumer.HandlerRetries попыток. Это единственный выход из «отравленного»
// сообщения, кроме остановки партиции.
//
// Возврат nil означает «я забрал сообщение» (записал в DLQ, в базу, в лог) —
// оффсет двигается дальше, сообщение считается skipped. Любая другая ошибка,
// как и отсутствие хука, означает «не забрал»: оффсет не двигается, партиция
// ставится на паузу, и после ребаланса или перезапуска сообщение приедет снова.
//
// Пауза, а не молчаливый пропуск, выбрана по умолчанию намеренно: коммит
// проваленного сообщения как skipped без хука означал бы потерю данных молча.
// Застрявшая партиция видна по лагу и по логу уровня Error, потеря — ничем.
//
// # Как вызывается
//
// Синхронно, из горутины партиционного воркера, и на всё время вызова партиция
// стоит: следующие сообщения не обрабатываются, а ребаланс, пришедший в этот
// момент, ждёт возврата из хука. Хук, живущий дольше
// Consumer.RebalanceTimeout, стоит группе исключения участника — то есть
// onLost вместо управляемого отзыва партиций.
//
// Паника внутри хука перехватывается и трактуется как «не забрал»: оффсет не
// двигается, партиция травится. Обратное — считать упавший хук забравшим —
// означало бы терять сообщение ровно тогда, когда его пытались спасти.
//
// # Контекст
//
// ctx — контекст обработки сообщения. Он отменяется при жёсткой остановке
// консьюмера и по истечении бюджета ожидания воркеров, то есть ровно во время
// shutdown, когда спасать сообщение и надо. Запись в DLQ с этим контекстом в
// такой момент провалится гарантированно.
//
// Поэтому внутри хука его следует отвязывать от отмены, оставляя себе
// собственный бюджет:
//
//	dlqCtx, cancel := context.WithTimeout(context.WithoutCancel(ctx), 5*time.Second)
//	defer cancel()
//
// Спан и trace-контекст при этом сохраняются: WithoutCancel снимает только
// отмену и дедлайн.
//
// # Владение памятью
//
// msg.Key и msg.Value — те же самые срезы, что видел обработчик, а не копии;
// см. IncomingMessage, раздел «Владение памятью». Читать их здесь безопасно,
// мутировать — нельзя.
type SkipHook func(ctx context.Context, msg IncomingMessage, cause error) error

// Option — параметр поведения клиента, передаваемый NewProducer, NewConsumer
// или Config.Validate.
//
// Интерфейс закрыт неэкспортируемым методом: реализовать Option снаружи нельзя,
// и набор законных значений — ровно конструкторы With* этого пакета. Иначе
// «опция» из чужого пакета молча не применялась бы ни к чему.
//
// Опция, применённая дважды, побеждает прежним значением последней. Исключение
// — WithExtraOpts: у него список накапливается, см. его godoc.
type Option interface {
	// applyTo применяет опцию к разобранному набору или объясняет, почему она
	// к этой роли не относится.
	applyTo(*behavior) error
}

// role — роль создаваемого клиента. Битовая маска, потому что у опции ролей
// может быть несколько: WithLogger осмыслен и для продюсера, и для консьюмера,
// а WithSkipHook — только для второго.
type role uint8

const (
	roleProducer role = 1 << iota
	roleConsumer

	// roleAny — обе роли сразу. Это Config.Validate: она проверяет и
	// продюсерскую секцию, и консьюмерскую, поэтому и опции принимает любые.
	roleAny = roleProducer | roleConsumer
)

// String даёт имя роли для сообщений об ошибке. Совпадает с subject агрегата
// валидации («producer config», «consumer config»), чтобы обе ошибки старта
// называли роль одинаково.
func (r role) String() string {
	switch r {
	case roleProducer:
		return "producer"
	case roleConsumer:
		return "consumer"
	case roleAny:
		return "producer or consumer"
	default:
		return fmt.Sprintf("role(%d)", uint8(r))
	}
}

// behavior — разобранный набор Option: то самое поведение, которое раньше
// лежало в Config.
//
// Собирается newBehavior один раз в конструкторе и дальше только читается.
// Единственное исключение — logger: конструктор подменяет его производным, с
// проставленным component, и с этого момента поле означает «логгер этого
// клиента», а не «логгер, который передал вызывающий». Признак «логгер задан»
// в сводке опций не публикуется намеренно (см. LogValue), так что подмена
// ничего не искажает.
type behavior struct {
	// role — роль, для которой набор собран. Нужна применению опций: она и
	// отличает «WithSkipHook у консьюмера» от «WithSkipHook у продюсера».
	role role

	logger    *slog.Logger
	tlsConfig *tls.Config
	extraOpts []kgo.Opt
	panicHook PanicHook
	skipHook  SkipHook
}

// newBehavior разбирает опции для роли r.
//
// Ошибки собираются все разом, а не возвращаются по первой — по той же
// причине, что и в Config.Validate: иначе набор опций чинится по одной за
// перезапуск. Разбор при этом не прерывается: набор всё равно возвращается
// частично применённым, но пользоваться им вызывающий не должен — конструкторы
// выходят по ошибке раньше.
func newBehavior(r role, opts ...Option) (behavior, error) {
	b := behavior{role: r}

	var errs []error

	for i, opt := range opts {
		// nil в списке — не «пустая опция», а почти наверняка результат
		// вызова, вернувшего nil вместо Option. Молча пропустить его значило
		// бы потерять настройку без единого следа.
		if opt == nil {
			errs = append(errs, fmt.Errorf("%w: option #%d", ErrNilOption, i))

			continue
		}

		if err := opt.applyTo(&b); err != nil {
			errs = append(errs, err)
		}
	}

	return b, errors.Join(errs...)
}

// LogValue публикует сводку набора: что задано и сколько.
//
// Сюда переехали четыре признака, которые до разделения печатала
// Config.LogValue: tls_config_set и extra_opts под теми же именами, on_panic_set
// и on_message_skipped_set — под panic_hook_set и skip_hook_set, по именам
// опций, которыми хуки теперь задаются.
//
// Значения самих опций в лог не помещаются: собранный *tls.Config и замыкания
// хуков нечитаемы. Но факт, что хук задан, объясняет поведение, которого не
// видно больше нигде: с SkipHook отравленное сообщение пропускается, без него
// партиция встаёт.
//
// Признака «логгер задан» здесь нет намеренно, и не было в Config.LogValue:
// запись читают через тот самый логгер, о котором она сообщала бы.
//
// Хуки печатаются только консьюмеру: продюсеру их задать нельзя (см.
// WithPanicHook), и строка panic_hook_set=false в его логе означала бы
// «настройка есть, но выключена» вместо «настройки не существует».
func (b behavior) LogValue() slog.Value {
	attrs := []slog.Attr{
		slog.Bool("tls_config_set", b.tlsConfig != nil),
		slog.Int("extra_opts", len(b.extraOpts)),
	}

	if b.role&roleConsumer != 0 {
		attrs = append(attrs,
			slog.Bool("panic_hook_set", b.panicHook != nil),
			slog.Bool("skip_hook_set", b.skipHook != nil))
	}

	return slog.GroupValue(attrs...)
}

// option — единственная реализация Option.
//
// Одна структура на все конструкторы, а не тип на опцию: различаются они только
// именем, набором ролей и присваиванием, и пять почти одинаковых типов ничего к
// этому не добавили бы.
type option struct {
	// name — имя конструктора, как его написал вызывающий. Идёт в текст
	// ошибки: «WithSkipHook applies to…» отправляет читателя ровно к той
	// строке, которую надо убрать.
	name string
	// roles — роли, к которым опция применима.
	roles role
	set   func(*behavior)
}

// applyTo отвергает опцию, не относящуюся к роли, вместо того чтобы молча её
// проглотить.
//
// Тихий пропуск здесь был бы худшим из исходов: WithSkipHook, переданный
// продюсеру, выглядит как настроенная выдача отравленных сообщений в DLQ, а на
// деле не делает ничего — и узнают об этом не при старте, а когда сообщение
// потребуется спасать. Отдельные типы опций на роль поймали бы это
// компилятором, но развели бы WithLogger и WithTLSConfig на две одинаковые
// пары; отказ при создании ловит ту же ошибку в первую же секунду жизни
// процесса и оставляет один тип Option на оба конструктора.
func (o option) applyTo(b *behavior) error {
	if o.roles&b.role == 0 {
		return fmt.Errorf("%w: %s applies to the %s, but was passed to the %s constructor",
			ErrInapplicableOption, o.name, o.roles, b.role)
	}

	o.set(b)

	return nil
}

// WithLogger задаёт логгер библиотеки. Без него используется slog.Default().
// Логи самого franz-go пишутся в него же, но не ниже Config.KafkaLogLevel.
func WithLogger(logger *slog.Logger) Option {
	return option{
		name:  "WithLogger",
		roles: roleAny,
		set:   func(b *behavior) { b.logger = logger },
	}
}

// WithTLSConfig задаёт готовый *tls.Config. Он имеет приоритет над секцией
// Config.TLS целиком: сборка конфигурации из путей к файлам покрывает типовой
// случай, но не покрывает mTLS с ротацией, кастомный VerifyPeerCertificate или
// сертификаты из памяти.
//
// Валидация судит о том же соединении, которое соберётся: с этой опцией
// SASL PLAIN считается защищённым и без Config.TLS.Enabled.
func WithTLSConfig(cfg *tls.Config) Option {
	return option{
		name:  "WithTLSConfig",
		roles: roleAny,
		set:   func(b *behavior) { b.tlsConfig = cfg },
	}
}

// WithExtraOpts добавляет опции franz-go. Они приписываются к опциям клиента
// последними и потому побеждают всё, что вывела библиотека. Аварийный выход для
// настроек, которые kafkax не покрывает, — не замена конфигурации.
//
// В отличие от прочих опций, повторный вызов не заменяет прежний список, а
// продолжает его: WithExtraOpts — это и есть список, и «последний вызов
// победил» терял бы опции, добавленные из другого места сборки конфигурации.
//
// kgo.WithPools здесь не поддерживается: пулинг требует вызова Record.Recycle,
// которого пакет не делает, поэтому включённый так пул просто перестанет
// возвращать память. См. IncomingMessage, раздел «Владение памятью».
func WithExtraOpts(opts ...kgo.Opt) Option {
	return option{
		name:  "WithExtraOpts",
		roles: roleAny,
		set:   func(b *behavior) { b.extraOpts = append(b.extraOpts, opts...) },
	}
}

// WithPanicHook задаёт PanicHook — реакцию на восстановленную панику в горутине
// библиотеки.
//
// Только для консьюмера: собственных горутин у продюсера нет, восстанавливать
// панику негде и не из чего — она уходит вызывающему по его же стеку.
// NewProducer с этой опцией возвращает ошибку ErrInapplicableOption, а не
// принимает хук, который никогда не будет вызван.
func WithPanicHook(hook PanicHook) Option {
	return option{
		name:  "WithPanicHook",
		roles: roleConsumer,
		set:   func(b *behavior) { b.panicHook = hook },
	}
}

// WithSkipHook задаёт SkipHook — судьбу сообщения, которое обработчик не осилил
// за Consumer.HandlerRetries попыток.
//
// Только для консьюмера: у продюсера нет ни обработчиков, ни повторов, ни
// отравленных сообщений. NewProducer с этой опцией возвращает ошибку
// ErrInapplicableOption.
func WithSkipHook(hook SkipHook) Option {
	return option{
		name:  "WithSkipHook",
		roles: roleConsumer,
		set:   func(b *behavior) { b.skipHook = hook },
	}
}
