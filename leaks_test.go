// Проверка на утечку горутин по всему пакету.
//
// Пакет плодит горутины на каждом шагу: цикл опроса, партиционные воркеры,
// watchContext, внутренние горутины franz-go и kfake. Ни одна из них не видна
// из публичного API — Stop и Close возвращают ошибку, а не число оставшихся
// горутин, — поэтому утечка не роняет ни один тест. В долгоживущем сервисе,
// который создаёт консьюмера на каждую подписку, она проявляется только ростом
// памяти через сутки работы.
//
// Проверка стоит на TestMain, а не на каждом тесте через VerifyNone, по двум
// причинам. Дешевизна: один снимок на весь прогон вместо снимка на тест.
// И правильные границы: t.Cleanup останавливает консьюмера в конце теста, но
// горутины franz-go доживают до закрытия клиента, а kfake — до Close кластера,
// так что потестовая проверка ловила бы штатное «ещё не догасло» и требовала бы
// списка исключений длиннее самой проверки.
//
// Список IgnoreTopFunction пуст намеренно, и это его главное свойство: сейчас
// пакет и все его зависимости гасят за собой всё до последней горутины.
// Первая же строка исключения означает, что кто-то этого делать перестал, —
// прежде чем добавлять её, стоит убедиться, что оставшаяся горутина
// действительно чужая и действительно конечна.
func TestMain(m *testing.M) {
	goleak.VerifyTestMain(m)
}
