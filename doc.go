// Package kafkax предоставляет продюсер и консьюмер Kafka с изоляцией по
// партициям, OpenTelemetry-трейсингом и метриками «из коробки».
//
// Пакет построен на github.com/twmb/franz-go — чистом Go-клиенте, без cgo:
// сборка статическая, кросс-компиляция обычная, детектор гонок видит весь код.
//
// # Гарантии доставки
//
// Консьюмер даёт at-least-once. Оффсет отмечается к коммиту (MarkCommitRecords)
// только после того, как обработчик вернул nil, а фоновый коммит отправляет
// брокеру исключительно отмеченное. Обычный автокоммит по времени двигал бы
// оффсет по факту чтения, а не обработки, и превращал бы гарантию в
// at-most-once при падении процесса.
//
// Следствие, о котором нужно знать при внедрении: дубликаты возможны и штатны.
// Сообщение, обработанное непосредственно перед падением или ребалансом, будет
// обработано повторно. Обработчик обязан быть идемпотентным — библиотека
// exactly-once не даёт и дать не может.
//
// # Политика повторов
//
// Это то место, где умолчания пакета отличаются от привычных, и отличаются
// намеренно. Прочитайте раздел целиком, прежде чем выкатывать пакет в прод.
//
// Когда ConsumerHandler.ProcessMessage возвращает ошибку, сообщение проходит
// два независимых этапа: повторы и разрешение отказа.
//
// Этап 1 — повторы. Управляется Consumer.HandlerRetries и
// Consumer.HandlerRetryDelay:
//
//	 0 (умолчание)  вызвать обработчик один раз, повторов не делать
//	 N > 0          сделать N повторов сверх первого вызова, всего N+1 вызовов
//	-1              повторять бесконечно
//
// Повторы происходят в горутине партиционного воркера и блокируют партицию:
// пока сообщение повторяется, следующие сообщения этой же партиции ждут. Это
// цена сохранения порядка, а не недосмотр. HandlerRetries = -1 означает, что
// партиция будет заблокирована до тех пор, пока обработчик не вернёт nil или
// консьюмер не остановят; этап 2 при этом не наступает никогда.
//
// Паника обработчика превращается в обычную ошибку и проходит те же повторы, но
// рапортуется один раз на сообщение, а не на попытку: стек в лог, инкремент
// kafkax.consumer.panics{site="handler"} и вызов хука WithPanicHook случаются на
// первой попытке. Иначе при HandlerRetries = -1 счётчик рос бы линейно во
// времени, а не по событиям, и «одно сообщение крутится сутки» стало бы
// неотличимо от «упало N разных сообщений». Что повторы всё-таки идут, видно по
// kafkax.consumer.handler.retries и по записям уровня Warn.
//
// Этап 2 — разрешение отказа. Наступает, когда повторы исчерпаны. Исходов два,
// и выбирает между ними наличие хука WithSkipHook:
//
//	WithSkipHook задан и вернул nil
//	    Сообщение считается пропущенным: оффсет отмечается, коммит двигается
//	    дальше, партиция продолжает работу. Метрика — status="skipped", в лог
//	    пишется одна запись уровня Warn. Возврат nil — это заявление «я забрал
//	    сообщение»: записал в DLQ, в базу, в лог. Пустой хук, возвращающий nil,
//	    — это молчаливая потеря данных.
//
//	WithSkipHook не задан, вернул ошибку или запаниковал
//	    Оффсет НЕ отмечается, партиция ставится на паузу (PauseFetchPartitions)
//	    и остаётся на непрокоммиченном оффсете. Метрика — status="error", в лог
//	    пишется одна запись уровня Error. Сообщение приедет снова после ребаланса
//	    или перезапуска процесса. Остальные партиции продолжают работать.
//
// Уровень записи выбирает только второй этап, и это контракт, а не деталь
// реализации: при работающем WithSkipHook отказ обработчика — штатный исход,
// и Error на нём давал бы постоянный фон Error при полностью исправной работе.
// Один отказ даёт одну запись: число попыток, причина и ветка разрешения
// приезжают в неё атрибутами, а не отдельными строками.
//
// Умолчание — второй вариант: без хука отравленное сообщение останавливает свою
// партицию, а не пропускается. Выбор сделан сознательно. Застрявшая партиция
// видна сразу — по растущему лагу, по kafkax.consumer.messages.processed со
// status="error" и по логу; потерянное сообщение не видно ничем. Пропуск —
// это явное действие потребителя пакета, а не то, что случается само.
//
// Пауза снимается в момент, когда партиция назначается консьюмеру снова —
// ребалансом или перезапуском процесса, — то есть тогда же, когда она начнёт
// читаться с проваленного оффсета заново. Отдельного API для снятия паузы нет
// намеренно: возобновить чтение, не разобравшись с причиной, значит вернуться
// в тот же цикл.
//
// Пока партиция стоит, kafkax.consumer.partitions.paused держит ненулевое
// значение. Это гейдж, а не счётчик событий: алерт «стоит хотя бы одна
// партиция» строится только по нему, разовая запись в логе к моменту дежурства
// уже уедет из окна. Записи, которые воркер успел вычитать до паузы, он
// выбрасывает, не отмечая, — их видно как status="dropped".
//
// Второй, редкий повод для той же паузы — смерть партиционного воркера от
// паники в его собственной горутине (kafkax.consumer.panics с
// site="partition_worker"). Обрабатывать партицию некому, поэтому она выводится
// из выборки на непрокоммиченном оффсете, а приехавшие батчи учитываются как
// status="dropped". Молчаливая альтернатива — продолжать вычитывать партицию в
// никуда — снаружи неотличима от «в топик просто не пишут».
//
// Третий повод — рассинхрон подписки и карты обработчиков. В обычной сборке он
// невозможен: набор топиков выводится из зарегистрированных обработчиков.
// Устроить его может только WithExtraOpts, чьи опции добавляются к опциям
// клиента последним и перекрывает выведенную подписку, — типично через
// kgo.ConsumeRegex или собственный kgo.ConsumeTopics. Запись из топика без
// обработчика идёт тем же путём, что и отравление: оффсет не отмечается,
// партиция встаёт, в лог уходит одна запись Error с атрибутом
// reason="subscription and handler map are out of sync", метрика —
// status="error".
//
// Реакция именно такая, а не «пропустить незнакомое сообщение», потому что
// пропуск означал бы потерю данных из-за ошибки в конфигурации, и притом
// бесшумную. Восстановление — только вне процесса: AddHandler после Start
// отвергается (ErrConsumerStarted), консьюмер, прошедший Stop, не
// перезапускается. Чинится конфигурация, и поднимается новый экземпляр —
// партиция достанется ему назначением, и пауза снимется вместе с созданием
// свежего воркера.
//
// Важно: пока партиция остаётся за тем же экземпляром и ребаланса не
// происходит, отравленное сообщение НЕ приезжает заново само по себе. В
// однопроцессном развёртывании это означает: до перезапуска (или до входа в
// группу второго экземпляра) партиция стоит. Признак — растущий лаг без новых
// записей уровня Error: сообщение до обработчика больше не доходит, поэтому и
// счётчик status="error" перестаёт расти.
//
// Практический вывод для внедрения. Осмысленных конфигураций три:
//
//	Порядок важнее прогресса, потеря недопустима:
//	    HandlerRetries: -1 — партиция ждёт столько, сколько нужно.
//
//	Потеря недопустима, но зависать в обработчике нельзя:
//	    HandlerRetries: N, хука WithSkipHook нет — партиция встаёт на паузу,
//	    инцидент разбирает дежурный. Это умолчание.
//
//	Прогресс важнее отдельного сообщения:
//	    HandlerRetries: N, WithSkipHook: запись в DLQ и возврат nil.
//	    Единственный вариант, в котором конвейер не останавливается никогда.
//
// Отдельный случай: если контекст отменён во время паузы между повторами
// (идёт остановка консьюмера), сообщение не отмечается и партицию не травит —
// оно просто приедет снова. Метрика — status="cancelled", отдельно от skipped
// именно потому, что коммит здесь НЕ двигается: skipped означает потерянное
// сообщение, cancelled случается на каждом штатном деплое. Длительность под
// этим статусом не пишется — обработка не закончилась, мерить нечего.
//
// # Продюсер
//
// Producer.SendMessage синхронен и потокобезопасен: параллельные вызовы
// батчатся внутри franz-go, поэтому «синхронный» не означает «по запросу на
// сообщение». Весь путь отправки ограничен одним бюджетом —
// Producer.MessageTimeout, отсчитываемым от входа в метод. Дедлайн переданного
// ctx этот бюджет только сокращает: срабатывает тот из двух, который наступит
// раньше, и в обоих случаях вызывающий получает ErrDeliveryTimeout с
// context.DeadlineExceeded под ним. Отмена ctx — это context.Canceled без
// сентинела пакета: отправку отменил вызывающий, а не Kafka.
//
// С оговоркой, важной для кода с собственным жёстким дедлайном: при
// Producer.EnableIdempotence = true (умолчание) этот бюджет не является ни
// гарантией отмены записи, ни верхней границей ожидания вызывающим. Провалить
// запись, уже находящуюся в полёте, franz-go не может — это оставило бы дыру в
// последовательности sequence numbers и сломало бы порядок. Но пока судьба
// батча неизвестна, не исполняется и само решение «пора завалить»: срок
// признаётся истёкшим и тут же откладывается, раз за разом, пока партиция не
// станет доступна. Дедлайн переданного ctx упирается в тот же запрет и границы
// тоже не даёт.
//
// Измерено на кластере с потерянным лидером партиции: при MessageTimeout = 5s
// вызов не вернулся ни через 60, ни через 150 секунд. Тому, кому нужна именно
// граница ожидания, ctx не поможет — нужно либо не блокироваться на вызове,
// либо Producer.EnableIdempotence = false, при котором бюджет жёсткий: порядок
// терять уже нечего.
//
// Ошибки отправки делятся по одному признаку — можно ли повторить, не рискуя
// дубликатом. ErrProducerClosed означает «сообщение точно не ушло»,
// ErrDeliveryTimeout — «могло уйти, повтор способен создать дубликат»,
// ErrDeliveryFailed — «брокер отверг», и решение о повторе зависит от кода
// отказа. Причина развёрнута рядом с сентинелом во всех трёх случаях: сентинел
// отвечает на вопрос «повторять ли», причина — «что именно случилось».
//
// # Подтверждённая запись при смене лидера партиции
//
// nil из SendMessage означает «брокер ответил успехом», и в одном сценарии
// этого недостаточно. При Producer.EnableIdempotence = true (умолчание) и
// КОНЕЧНОМ Producer.MaxRetries подтверждённой записи может не оказаться в теме.
// Не «пока не оказаться»: её там не будет никогда, повторное чтение не
// помогает, счётчик kafkax.producer.messages.sent считает её доставленной.
//
// Умолчание Producer.MaxRetries — -1, «без ограничения», и выбрано оно ровно
// поэтому. Раздел остаётся здесь, потому что лимит вправе поставить
// вызывающий, а последствие лимита неочевидно.
//
// Механизм лежит ниже kafkax и воспроизведён на голом franz-go с теми же
// опциями, которые строит пакет. Брокер, потерявший лидерство уже после того,
// как дописал батч в свой лог, отвечает отказом not_leader_or_follower, но
// оставляет в ответе оффсет сделанной записи: запись сохранена, а клиент
// считает её несостоявшейся. Лимит повторов исчерпывается за сотни
// миллисекунд — быстрее, чем идут перевыборы, — franz-go заваливает батч
// ошибкой и отдаёт его sequence number СЛЕДУЮЩЕЙ записи. Для брокера этот
// номер уже свой: он отвечает успехом с оффсетом первой записи и вторую не
// пишет. Вызывающий получает nil на запись, которой в теме нет.
//
// Измерено на кластере из трёх узлов с RF = 3, min.insync.replicas = 2 и
// выключенными нечистыми выборами: 2 отказа на 18 прогонов через kafkax и 3 на
// 47 через сырой kgo, каждый раз ровно одна подтверждённая запись отсутствует
// и ровно одна НЕподтверждённая лежит. Разбор, логи и ссылки на исходник
// franz-go — в docs/audit/09-mutation-sweep.md.
//
// Средства, закрывающего сценарий полностью, у пакета нет: батч заваливает не
// только лимит повторов, но и Producer.MessageTimeout, а переиспользование
// номера одинаково следует из обоих. Умолчание «без ограничения» переносит
// окно с сотен миллисекунд на MessageTimeout, то есть за пределы обычных
// перевыборов: измерено 0 отказов на 20 прогонов против 2 на 18 при
// MaxRetries = 3.
//
// Платят за это диагностикой, и плата настоящая. ВСЯКИЙ отказ, случившийся до
// того, как батч ушёл брокеру, конечный лимит обрывал быстро — измерено ~16 с
// при MaxRetries = 3 и для недоверенного корня TLS, и для неверного пароля.
// Без лимита оба живут до конца Producer.MessageTimeout: окончательным клиент
// не признаёт даже отказ аутентификации. Причина при этом доезжает — franz-go
// вкладывает последнюю ошибку попытки внутрь таймаута доставки, — но
// обнаруживается позже. Кому нужен быстрый отказ, сокращает MessageTimeout:
// «сколько ждать до отказа» — это бюджет времени, и число попыток было для
// него плохой заменой.
//
// На записи, уже отданной брокеру, лимит и раньше ничего не решал: там
// SendMessage не ограничен ни MessageTimeout, ни дедлайном ctx.
//
// Producer.EnableIdempotence = false убирает сам номер, а вместе с ним и
// переиспользование, но взамен возвращает дубликаты и перестановки; измерением
// это не проверялось.
//
// # Разбор ошибок и типы franz-go
//
// Типы github.com/twmb/franz-go частью публичного контракта kafkax НЕ являются.
// Это сказано утверждением, а не умолчанием: пакет уже пережил одну смену
// клиента, а зависимость на чужой тип ошибки ломается молча — ни одна сигнатура
// при такой смене не меняется, поэтому компилятор промолчит, а errors.As просто
// перестанет находить.
//
// Всё, что нужно для решения о повторе, лежит в DeliveryError:
//
//	var derr *kafkax.DeliveryError
//	if errors.As(err, &derr) && derr.Retriable {
//		// брокер считает отказ временным
//	}
//
// Ошибка клиента остаётся достижимой через Unwrap — для отладки и для того,
// чтобы errors.Is продолжал находить сентинелы franz-go в цепочке. Код,
// делающий errors.As до *kerr.Error, работает и сегодня, но переживёт смену
// клиента только случайно.
//
// # Жизненный цикл консьюмера
//
// Состояний три, а не два: «не запущен», «запущен», «остановлен навсегда».
// Переходы односторонние — консьюмер, прошедший Stop, не перезапускается, и
// Start с AddHandler на нём возвращают ErrConsumerClosed, а не
// ErrConsumerStarted. Различие практическое: ErrConsumerStarted значит «запуск
// уже произошёл, повторять не нужно», ErrConsumerClosed — «нужен новый
// консьюмер». Неуспешный Start (ErrNoHandlers, ошибка конфигурации) состояние
// не меняет: конфигурацию можно исправить и вызвать Start снова.
//
// У продюсера состояний два, «не запущен» у него нет: NewProducer отдаёт
// готовый к работе объект, а после Close всякий SendMessage возвращает
// ErrProducerClosed.
//
// # Ошибки остановки
//
// Close и Stop возвращают ошибку не для симметрии: два исхода означают потерю
// или дублирование данных. ErrFlushIncomplete — Close продюсера не успел
// дослать буфер, сообщения потеряны. ErrCommitFailed — финальный коммит не
// дошёл до брокера, обработанное приедет заново; для at-least-once это штатно,
// но дубликаты будут. Типовой defer producer.Close() обе теряет: если данные
// важны, возвращённое значение нужно читать.
//
// Величина потери — в поле, а не в тексте: errors.As до *FlushError отдаёт
// Remaining, число недосланных записей. Текст ошибки при этом один и тот же на
// любое их количество, иначе одна авария давала бы в APM столько групп,
// сколько раз она случилась.
//
// # Конфигурация
//
// DefaultConfig возвращает те же умолчания, что cleanenv подставляет из тегов
// env-default, — для кода, который конфигурацию из окружения не читает.
// Brokers, ClientID и Consumer.Group умолчания не имеют намеренно: значение по
// умолчанию у группы означало бы, что два забывших её задать сервиса молча
// делят один assignment.
//
// Валидация собирает все претензии разом, а не отдаёт первую: иначе неполный
// конфиг чинится по одному полю за перезапуск. Список разворачивается через
// Unwrap() []error, а вся ошибка опознаётся через errors.Is с ErrInvalidConfig
// — сам сентинел в список не входит, иначе печать претензий пользователю
// начиналась бы со строки «invalid configuration». Конструкторы отдают агрегат
// как есть: обёртка через fmt.Errorf подменила бы Unwrap() []error на
// Unwrap() error.
//
// Претензия называет поле Go-путём, а имя переменной окружения ставит следом в
// скобках: «Consumer.MaxBytes (env KAFKAX_CONSUMER_MAX_BYTES) must be positive,
// got 0». Config собирают и литералом в Go, и через cleanenv, и прежний
// yaml-путь обслуживал только второй способ — по нему нельзя найти поле в
// структуре. Yaml-ключ при этом остаётся выводимым: это тот же путь в snake_case.
//
// # Наблюдаемость
//
// Трассировка и транспортные метрики (соединения, байты, ошибки чтения и
// записи) приходят из kotel по семантическим соглашениям OTel. Доменные метрики
// пакета — с префиксом kafkax.: producer.messages.sent, producer.messages.failed,
// producer.messages.rejected, producer.message.duration,
// consumer.messages.processed, consumer.message.duration,
// consumer.handler.retries, consumer.fetch.errors, consumer.group.errors,
// consumer.workers.active, consumer.partitions.paused, consumer.panics,
// consumer.commit.errors, consumer.partitions.lost, consumer.drain.timeouts.
// Длительности — в секундах.
//
// Транспортный уровень измеряет kotel, но только счётчиками: гистограмм в
// kotel v1.7.0 нет ни одной, поэтому латентность запроса к брокеру и
// распределение размеров батчей не измеряет никто. Обе гистограммы пакета
// меряют путь через пакет, а не запрос.
//
// Последние три счётчика существуют потому, что каждое из этих событий
// означает потерю или дублирование данных, а до них жило только строкой в
// журнале: проваленный коммит на ребалансе — самый частый источник
// дубликатов, а исчерпанный бюджет дренажа означает, что GracefulTimeout мал
// для реального времени обработки. Там, где ошибка возвращается вызывающему
// (Stop, Close), пакет её НЕ логирует: иначе событие удваивалось бы в
// журнале, — поэтому возвращённое значение нужно читать, а алерты строить по
// счётчикам.
//
// Исключение ровно одно, и оно осознанное: ErrPollLoopStuck пишется в лог и
// возвращается одновременно. Возврат сообщает вызывающему факт, но не его
// последствие — открытый клиент, который переживёт Stop и останется в группе.
// Это состояние процесса, а не результат вызова, и место ему в журнале.
//
// producer.messages.rejected считает отбраковку на входе — пустой топик,
// негодные заголовки — и это единственная доменная метрика без атрибута topic:
// значение приходит из PublishRequest, то есть снаружи, и серия на каждое
// уникальное уронила бы backend метрик ровно теми запросами, которые пакет
// отверг не глядя. Вместо topic у неё замкнутый reason.
//
// consumer.fetch.errors и consumer.group.errors считают эпизоды, а не опросы:
// неретраибельную ошибку franz-go возвращает на каждом опросе заново, поэтому
// инкремент делается на переходе «было здорово → сломалось» и на смену текста
// ошибки. Счётчик всех вхождений мерил бы частоту опроса, а не масштаб
// проблемы. Отказ уровня группы вынесен отдельно от партиционного: сообщений
// при нём нет вообще, ни по одной партиции, и алерт на него нужен свой.
//
// У consumer.fetch.errors есть граница, о которой нужно знать, прежде чем
// строить на нём алерт «данные пропали»: на усечении темы он молчит. Если
// закоммиченный группой оффсет оказался ниже начала лога (retention или
// администратор удалил записи), брокер отвечает OFFSET_OUT_OF_RANGE, но наверх
// эта ошибка не приходит — franz-go обрабатывает её сам, сбрасывая позицию на
// Consumer.InitialOffset, и до счётчика ничего не доходит. Записи между
// закоммиченным оффсетом и новым началом лога до обработчика не дойдут никогда,
// а при InitialOffset=latest потеряется и весь неотставший хвост. Снаружи поток
// при этом выглядит здоровым: лаг нулевой, ошибок нет. Алерт на этот случай
// строится не по метрикам пакета, а по разрыву между закоммиченным оффсетом
// группы и log start offset. Поведение закреплено интеграционным тестом
// (TestTruncationBelowCommittedOffset) и покраснеет, если franz-go начнёт
// отдавать эту ошибку наверх.
//
// Атрибута partition нет ни у одной метрики: он умножает кардинальность на
// число партиций, не давая ничего сверх того, что уже есть в спане.
//
// Имена атрибутов доменных метрик (topic, status) от messaging semantic
// conventions отклоняются намеренно: они короче в PromQL, а привязку к
// конвенциям даёт спан, где те же поля есть под каноническими именами. Плата —
// корреляция «спан ↔ метрика» по имени атрибута не работает. По той же причине
// scope метрик объявлен с версией, но без SchemaURL: заявить соответствие
// схеме и не следовать ей хуже, чем не заявлять.
//
// consumer.panics размечен атрибутом site — точкой восстановления, тип
// PanicSite. Значение site="on_panic" означает, что упал сам хук WithPanicHook:
// повторно он в этом случае не вызывается (рекурсия в обработчике паник
// кончилась бы переполнением стека), но лог со стеком и инкремент счётчика
// пишутся — компонент, сигнализирующий об авариях, не имеет права отказывать
// молча.
//
// # Контекст обработчика
//
// В ConsumerHandler.ProcessMessage приходит контекст воркера: его отмена —
// сигнал остановки, и обработчик обязан её уважать. В этот контекст перенесены
// спан обработки и baggage, извлечённый propagator'ом из заголовков записи, —
// так tenant_id, request_id и прочая разметка вызывающей стороны доезжают до
// обработчика и до его собственных спанов. Пустое baggage в контекст не
// кладётся.
//
// Значения baggage приходят от внешнего отправителя. В атрибуты метрик пакета
// они не попадают ни при каких условиях: кардинальность оттуда не растёт.
