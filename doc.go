// Package kafkax предоставляет продюсер и консьюмер Kafka с изоляцией по
// партициям, OpenTelemetry-трейсингом и метриками «из коробки».
//
// Пакет построен на github.com/twmb/franz-go — чистом Go-клиенте, без cgo:
// сборка статическая, кросс-компиляция обычная, детектор гонок видит весь код.
//
// # Гарантии доставки
//
// Консьюмер даёт at-least-once. Оффсет отмечается к коммиту (MarkCommitRecords)
// только после того, как обработчик вернул nil, а фоновый коммит отправляет
// брокеру исключительно отмеченное. Обычный автокоммит по времени двигал бы
// оффсет по факту чтения, а не обработки, и превращал бы гарантию в
// at-most-once при падении процесса.
//
// Следствие, о котором нужно знать при внедрении: дубликаты возможны и штатны.
// Сообщение, обработанное непосредственно перед падением или ребалансом, будет
// обработано повторно. Обработчик обязан быть идемпотентным — библиотека
// exactly-once не даёт и дать не может.
//
// # Политика повторов
//
// Это то место, где умолчания пакета отличаются от привычных, и отличаются
// намеренно. Прочитайте раздел целиком, прежде чем выкатывать пакет в прод.
//
// Когда ConsumerHandler.ProcessMessage возвращает ошибку, сообщение проходит
// два независимых этапа: повторы и разрешение отказа.
//
// Этап 1 — повторы. Управляется Consumer.HandlerMaxRetries и
// Consumer.HandlerRetryDelay:
//
//	 0 (умолчание)  вызвать обработчик один раз, повторов не делать
//	 N > 0          сделать N повторов сверх первого вызова, всего N+1 вызовов
//	-1              повторять бесконечно
//
// Повторы происходят в горутине партиционного воркера и блокируют партицию:
// пока сообщение повторяется, следующие сообщения этой же партиции ждут. Это
// цена сохранения порядка, а не недосмотр. HandlerMaxRetries = -1 означает, что
// партиция будет заблокирована до тех пор, пока обработчик не вернёт nil или
// консьюмер не остановят; этап 2 при этом не наступает никогда.
//
// Этап 2 — разрешение отказа. Наступает, когда повторы исчерпаны. Исходов два,
// и выбирает между ними наличие Config.OnMessageSkipped:
//
//	OnMessageSkipped задан и вернул nil
//	    Сообщение считается пропущенным: оффсет отмечается, коммит двигается
//	    дальше, партиция продолжает работу. Метрика — status="skipped".
//	    Возврат nil — это заявление «я забрал сообщение»: записал в DLQ, в базу,
//	    в лог. Пустой хук, возвращающий nil, — это молчаливая потеря данных.
//
//	OnMessageSkipped не задан, вернул ошибку или запаниковал
//	    Оффсет НЕ отмечается, партиция ставится на паузу (PauseFetchPartitions)
//	    и остаётся на непрокоммиченном оффсете. Метрика — status="error", в лог
//	    пишется запись уровня Error. Сообщение приедет снова после ребаланса
//	    или перезапуска процесса. Остальные партиции продолжают работать.
//
// Умолчание — второй вариант: без хука отравленное сообщение останавливает свою
// партицию, а не пропускается. Выбор сделан сознательно. Застрявшая партиция
// видна сразу — по растущему лагу, по kafkax.consumer.messages.processed со
// status="error" и по логу; потерянное сообщение не видно ничем. Пропуск —
// это явное действие потребителя пакета, а не то, что случается само.
//
// Пауза снимается в момент, когда партиция назначается консьюмеру снова —
// ребалансом или перезапуском процесса, — то есть тогда же, когда она начнёт
// читаться с проваленного оффсета заново. Отдельного API для снятия паузы нет
// намеренно: возобновить чтение, не разобравшись с причиной, значит вернуться
// в тот же цикл.
//
// Пока партиция стоит, kafkax.consumer.partitions.paused держит ненулевое
// значение. Это гейдж, а не счётчик событий: алерт «стоит хотя бы одна
// партиция» строится только по нему, разовая запись в логе к моменту дежурства
// уже уедет из окна. Записи, которые воркер успел вычитать до паузы, он
// выбрасывает, не отмечая, — их видно как status="dropped".
//
// Важно: пока партиция остаётся за тем же экземпляром и ребаланса не
// происходит, отравленное сообщение НЕ приезжает заново само по себе. В
// однопроцессном развёртывании это означает: до перезапуска (или до входа в
// группу второго экземпляра) партиция стоит. Признак — растущий лаг без новых
// записей уровня Error: сообщение до обработчика больше не доходит, поэтому и
// счётчик status="error" перестаёт расти.
//
// Практический вывод для внедрения. Осмысленных конфигураций три:
//
//	Порядок важнее прогресса, потеря недопустима:
//	    HandlerMaxRetries: -1 — партиция ждёт столько, сколько нужно.
//
//	Потеря недопустима, но зависать в обработчике нельзя:
//	    HandlerMaxRetries: N, OnMessageSkipped: nil — партиция встаёт на паузу,
//	    инцидент разбирает дежурный. Это умолчание.
//
//	Прогресс важнее отдельного сообщения:
//	    HandlerMaxRetries: N, OnMessageSkipped: запись в DLQ и возврат nil.
//	    Единственный вариант, в котором конвейер не останавливается никогда.
//
// Отдельный случай: если контекст отменён во время паузы между повторами
// (идёт остановка консьюмера), сообщение не отмечается и партицию не травит —
// оно просто приедет снова. Метрика — status="cancelled", отдельно от skipped
// именно потому, что коммит здесь НЕ двигается: skipped означает потерянное
// сообщение, cancelled случается на каждом штатном деплое. Длительность под
// этим статусом не пишется — обработка не закончилась, мерить нечего.
//
// # Продюсер
//
// KafkaProducer.SendMessage синхронен и потокобезопасен: параллельные вызовы
// батчатся внутри franz-go, поэтому «синхронный» не означает «по запросу на
// сообщение». Весь путь отправки ограничен одним бюджетом —
// Producer.MessageTimeout, отсчитываемым от входа в метод.
//
// Ошибки отправки делятся по одному признаку — можно ли повторить, не рискуя
// дубликатом. ErrProducerClosed означает «сообщение точно не ушло»,
// ErrDeliveryTimeout — «могло уйти, повтор способен создать дубликат»,
// ErrDeliveryFailed — «брокер отверг», и решение о повторе зависит от кода
// отказа. Причина развёрнута рядом с сентинелом во всех трёх случаях: сентинел
// отвечает на вопрос «повторять ли», причина — «что именно случилось».
//
// # Разбор ошибок и типы franz-go
//
// Типы github.com/twmb/franz-go частью публичного контракта kafkax НЕ являются.
// Это сказано утверждением, а не умолчанием: пакет уже пережил одну смену
// клиента, а зависимость на чужой тип ошибки ломается молча — ни одна сигнатура
// при такой смене не меняется, поэтому компилятор промолчит, а errors.As просто
// перестанет находить.
//
// Всё, что нужно для решения о повторе, лежит в DeliveryError:
//
//	var derr *kafkax.DeliveryError
//	if errors.As(err, &derr) && derr.Retriable {
//		// брокер считает отказ временным
//	}
//
// Ошибка клиента остаётся достижимой через Unwrap — для отладки и для того,
// чтобы errors.Is продолжал находить сентинелы franz-go в цепочке. Код,
// делающий errors.As до *kerr.Error, работает и сегодня, но переживёт смену
// клиента только случайно.
//
// # Жизненный цикл консьюмера
//
// Состояний три, а не два: «не запущен», «запущен», «остановлен навсегда».
// Переходы односторонние — консьюмер, прошедший Stop, не перезапускается, и
// Start с AddHandler на нём возвращают ErrConsumerClosed, а не
// ErrConsumerStarted. Различие практическое: ErrConsumerStarted значит «запуск
// уже произошёл, повторять не нужно», ErrConsumerClosed — «нужен новый
// консьюмер». Неуспешный Start (ErrNoHandlers, ошибка конфигурации) состояние
// не меняет: конфигурацию можно исправить и вызвать Start снова.
//
// У продюсера состояний два, «не запущен» у него нет: NewKafkaProducer отдаёт
// готовый к работе объект, а после Close всякий SendMessage возвращает
// ErrProducerClosed.
//
// # Ошибки остановки
//
// Close и Stop возвращают ошибку не для симметрии: два исхода означают потерю
// или дублирование данных. ErrFlushIncomplete — Close продюсера не успел
// дослать буфер, сообщения потеряны. ErrCommitFailed — финальный коммит не
// дошёл до брокера, обработанное приедет заново; для at-least-once это штатно,
// но дубликаты будут. Типовой defer producer.Close() обе теряет: если данные
// важны, возвращённое значение нужно читать.
//
// # Конфигурация
//
// DefaultConfig возвращает те же умолчания, что cleanenv подставляет из тегов
// env-default, — для кода, который конфигурацию из окружения не читает.
// Brokers, ClientID и Consumer.Group умолчания не имеют намеренно: значение по
// умолчанию у группы означало бы, что два забывших её задать сервиса молча
// делят один assignment.
//
// Валидация собирает все претензии разом, а не отдаёт первую: иначе неполный
// конфиг чинится по одному полю за перезапуск. Список разворачивается через
// Unwrap() []error, а вся ошибка опознаётся через errors.Is с ErrInvalidConfig
// — сам сентинел в список не входит, иначе печать претензий пользователю
// начиналась бы со строки «invalid configuration». Конструкторы отдают агрегат
// как есть: обёртка через fmt.Errorf подменила бы Unwrap() []error на
// Unwrap() error.
//
// # Наблюдаемость
//
// Трассировка и транспортные метрики (соединения, байты, ошибки чтения и
// записи) приходят из kotel по семантическим соглашениям OTel. Доменные метрики
// пакета — с префиксом kafkax.: producer.messages.sent, producer.messages.failed,
// producer.message.duration, consumer.messages.processed, consumer.message.duration,
// consumer.handler.retries, consumer.fetch.errors, consumer.group.errors,
// consumer.workers.active, consumer.partitions.paused, consumer.panics.
// Длительности — в секундах.
//
// consumer.fetch.errors и consumer.group.errors считают эпизоды, а не опросы:
// неретраибельную ошибку franz-go возвращает на каждом опросе заново, поэтому
// инкремент делается на переходе «было здорово → сломалось» и на смену текста
// ошибки. Счётчик всех вхождений мерил бы частоту опроса, а не масштаб
// проблемы. Отказ уровня группы вынесен отдельно от партиционного: сообщений
// при нём нет вообще, ни по одной партиции, и алерт на него нужен свой.
//
// Атрибута partition нет ни у одной метрики: он умножает кардинальность на
// число партиций, не давая ничего сверх того, что уже есть в спане.
